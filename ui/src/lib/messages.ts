/**
 * Typé explicitement plutôt qu'importé depuis `i18n.ts` : ce module est le
 * socle, il ne doit dépendre de rien pour rester libre de cycle d'import.
 */
export const CATALOGUES: {
  fr: Record<MessageKey, string>
  en: Record<MessageKey, string>
} = { fr, en }

/**
 * Clé de libellé i18n d'un niveau de sensibilité, avec repli sûr sur `standard`
 * si le backend annonçait un jour un niveau que l'UI ne traduit pas encore.
 * Garde le vocabulaire côté backend (`core/sensitivity`) sans le coder en dur.
 */
export function sensitivityLabelKey(level: string): MessageKey {
  const key = `sensitivity.${level}` as MessageKey
  return key in fr ? key : 'sensitivity.standard'
}

/**
 * Les faits de la réunion sont une option (`/api/config`, `faits`), coupée par défaut :
 * un texte qui les cite ne s'affiche que si elle est active, sinon il promettrait une
 * fonction absente.
 */
export function cleSelonFaits(cle: 'privacy.opens' | 'sensitivity.hint.ultra', faits: boolean) {
  return faits ? (`${cle}.faits` as const) : cle
}
