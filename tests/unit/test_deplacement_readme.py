def _norm(texte: str) -> str:
    """Liens réduits à leur texte, marques de citation et de gras retirées, espaces réduits : re-baser un lien
    d'un dossier à l'autre ou couper une ligne autrement ne change pas le sens."""
    texte = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", texte)
    texte = re.sub(r"(^|\n)[ \t]*>[ \t]?", r"\1", texte).replace("**", "")      # citations et gras : le texte seul
    return re.sub(r"\s+", " ", texte).strip()


@pytest.mark.parametrize("document", sorted(EXTRAITS))
def test_chaque_extrait_de_l_ancien_readme_se_retrouve_dans_son_document(document) -> None:
    chemin = RACINE / document
    assert chemin.is_file(), f"{document} n'existe pas"
    texte = _norm(chemin.read_text(encoding="utf-8"))
    extraits = EXTRAITS[document]
    assert len(extraits) >= 3, f"ancre : {document} a des extraits à retrouver"
    manquants = [x for x in extraits if _norm(x) not in texte]
    assert manquants == [], f"{document} : consigne(s) de l'ancien README absente(s) : {manquants[:5]}"


